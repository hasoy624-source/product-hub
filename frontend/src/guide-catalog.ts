export function isGuideRoute(route: string) {
  return route === 'guide' || guideTopics.some(topic => route === `guide/${topic.id}`)
}
export function guideTopicForRoute(route: string): GuideTopic {
  return guideTopics.find(topic => route === `guide/${topic.id}`) || guideTopics[0]
}
export function guideHrefFor(route: string) {
  const topic = guideTopics.find(topic => topic.destination === route.split('/')[0])
  return topic ? `#guide/${topic.id}` : '#guide'
}
export function filterGuideTopics(query: string) {
  const search = query.trim().toLocaleLowerCase()
  return guideTopics.filter(topic => JSON.stringify(topic).toLocaleLowerCase().includes(search))
}
